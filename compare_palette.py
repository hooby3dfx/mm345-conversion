def build_palette_lut(palette_a, palette_b):
    """
    palette_a and palette_b should be lists of 256 (R, G, B) tuples.
    """
    lut = {}
    
    for idx_a, color_a in enumerate(palette_a):
        r1, g1, b1 = color_a
        min_distance = float('inf')
        best_match_idx = 0
        
        for idx_b, color_b in enumerate(palette_b):
            r2, g2, b2 = color_b
            
            # Weighted Euclidean distance
            dr = r1 - r2
            dg = g1 - g2
            db = b1 - b2
            dist = (2 * dr**2) + (4 * dg**2) + (3 * db**2)
            
            if dist < min_distance:
                min_distance = dist
                best_match_idx = idx_b
                
        lut[idx_a] = best_match_idx
        
    return lut


